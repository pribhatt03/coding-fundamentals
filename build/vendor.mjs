#!/usr/bin/env node
// Puts everything the pages need into web/vendor/, so the course never has to
// reach another site: R (webR), the code editor (CodeMirror) and the fonts.
// That is what lets a learner save the course and use it offline.
//
//   webR        downloaded once from its GitHub release, checked against a
//               fixed SHA-256, then cached in .cache/ for later builds.
//   CodeMirror  copied from node_modules (pinned in package.json).
//   Fonts       copied from the @fontsource packages (pinned likewise).
//
// web/vendor/ is generated, so it's in .gitignore. Netlify runs this on
// every deploy.

import { mkdir, readFile, writeFile, cp, rm, stat, readdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { join } from "node:path";

const WEBR = {
  version: "0.6.0",
  url: "https://github.com/r-wasm/webr/releases/download/v0.6.0/webr-0.6.0.tar.gz",
  sha256: "04c56d16c3ad29265a2c4ffcb800ee0b72ab6dd64dd678c9c8fec81a832cb8cc",
};
const OUT = join("web", "vendor");
const CACHE = ".cache";

const exists = (p) => stat(p).then(() => true, () => false);
const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");

/* ------------------------------------------------------------------ webR --- */
async function webr() {
  const dest = join(OUT, "webr");
  const marker = join(dest, ".version");
  if ((await exists(marker)) && (await readFile(marker, "utf8")).trim() === WEBR.version) {
    return "webR " + WEBR.version + " (already in place)";
  }
  await mkdir(CACHE, { recursive: true });
  const tgz = join(CACHE, `webr-${WEBR.version}.tar.gz`);
  let buf = (await exists(tgz)) ? await readFile(tgz) : null;
  if (!buf || sha256(buf) !== WEBR.sha256) {
    const res = await fetch(WEBR.url);
    if (!res.ok) throw new Error(`couldn't download webR: ${res.status} ${WEBR.url}`);
    buf = Buffer.from(await res.arrayBuffer());
    if (sha256(buf) !== WEBR.sha256) {
      throw new Error(`webR download doesn't match its fingerprint — refusing to use it.\n` +
                      `  expected ${WEBR.sha256}\n  got      ${sha256(buf)}`);
    }
    await writeFile(tgz, buf);
  }
  await rm(dest, { recursive: true, force: true });
  await mkdir(dest, { recursive: true });
  // The release is webr-0.6.0/…; drop that top folder. Leave out webR's own
  // demo page, source maps, and the map-making libraries the course never uses.
  execFileSync("tar", [
    "-xzf", tgz, "-C", dest, "--strip-components=1",
    "--exclude=*/index.html", "--exclude=*/repl*", "--exclude=*/assets",
    "--exclude=*.map", "--exclude=*/vfs/usr/share/gdal*",
    "--exclude=*/vfs/usr/share/proj*", "--exclude=*/vfs/usr/share/udunits*",
  ], { stdio: ["ignore", "ignore", "ignore"] });   // macOS archives add harmless xattr warnings
  await writeFile(marker, WEBR.version + "\n");
  return "webR " + WEBR.version;
}

/* ------------------------------------------------------------ CodeMirror --- */
async function codemirror() {
  const src = join("node_modules", "codemirror");
  const dest = join(OUT, "codemirror");
  await rm(dest, { recursive: true, force: true });
  for (const f of ["lib/codemirror.js", "lib/codemirror.css", "mode/r/r.js",
                   "addon/edit/matchbrackets.js", "LICENSE"]) {
    await mkdir(join(dest, f, ".."), { recursive: true });
    await cp(join(src, f), join(dest, f));
  }
  const v = JSON.parse(await readFile(join(src, "package.json"), "utf8")).version;
  return "CodeMirror " + v;
}

/* ----------------------------------------------------------------- fonts --- */
// The same families and weights the pages used to load from Google Fonts.
const FONTS = [
  { family: "Literata",      pkg: "literata",      faces: [[400, "normal"], [600, "normal"], [400, "italic"]] },
  { family: "IBM Plex Sans", pkg: "ibm-plex-sans", faces: [[400, "normal"], [500, "normal"], [600, "normal"]] },
  { family: "IBM Plex Mono", pkg: "ibm-plex-mono", faces: [[400, "normal"], [500, "normal"], [400, "italic"]] },
];

async function fonts() {
  const dest = join(OUT, "fonts");
  await rm(dest, { recursive: true, force: true });
  await mkdir(dest, { recursive: true });
  let css = "/* Generated by build/vendor.mjs from the @fontsource packages. */\n";
  for (const f of FONTS) {
    const src = join("node_modules", "@fontsource", f.pkg);
    for (const [weight, style] of f.faces) {
      const file = `${f.pkg}-latin-${weight}-${style}.woff2`;
      await cp(join(src, "files", file), join(dest, file));
      css += `@font-face { font-family: "${f.family}"; font-style: ${style}; font-weight: ${weight};` +
             ` font-display: swap; src: url("./${file}") format("woff2"); }\n`;
    }
    const lic = (await readdir(src)).find((n) => /^LICEN[SC]E/i.test(n));
    if (lic) await cp(join(src, lic), join(dest, `LICENSE-${f.pkg}`));
  }
  await writeFile(join(dest, "fonts.css"), css);
  return "fonts " + FONTS.map((f) => f.family).join(", ");
}

/* -------------------------------------------------------------- licences --- */
async function licences() {
  await writeFile(join(OUT, "LICENSES.md"), `# Third-party software in this folder

This course hosts its own copies of the following, so it can run offline.
Each keeps its own licence.

- **webR ${WEBR.version}** — R compiled to WebAssembly. webR is MIT-licensed
  (Copyright Posit Software, PBC). It contains **R**, which is free software
  under the GNU General Public License, version 2 or 3. Source code for both:
  https://github.com/r-wasm/webr and https://www.r-project.org/.
  Downloaded from ${WEBR.url}
- **CodeMirror 5** — the code editor. MIT licence, in \`codemirror/LICENSE\`.
- **Literata, IBM Plex Sans, IBM Plex Mono** — fonts, via Fontsource. SIL Open
  Font License 1.1, in \`fonts/LICENSE-*\`.
`);
}

try {
  await mkdir(OUT, { recursive: true });
  const done = [await webr(), await codemirror(), await fonts()];
  await licences();
  console.log("vendored: " + done.join("; "));
} catch (e) {
  console.error("  FAIL  vendor: " + (e.message ?? e));
  process.exit(1);
}
